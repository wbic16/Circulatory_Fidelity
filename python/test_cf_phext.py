# --- Schema 2: marginal vs conditional coupling ----------------------------

CHAIN_SIGMA = np.array([[1.00, 0.60, 0.36],
                        [0.60, 1.00, 0.60],
                        [0.36, 0.60, 1.00]])


def _entry(path, vol, i, j, scroll):
    book = px.BOOK_D if i == j else px.BOOK_R
    section = 1 if i == j else j + 1
    return px.read_scroll(path, px.coord_str(px.addr(vol, book, i + 1, section, scroll)))


def test_chain_marginal_vs_conditional():
    """A-B-C chain: marginal corr(A,C)=0.36 is purely indirect (through
    B); partial corr(A,C)=0 because Lambda_AC=0. Schema 1 mixed these
    in one record (value ~0 next to ic=0.36); schema 2 stores both,
    labelled."""
    prec = np.linalg.inv(CHAIN_SIGMA)
    path = _tmp("chain.phext")
    vol = px.matrix_to_phext(prec, path, kind="precision")
    # A,C: value ~0, ic_marginal 0.36, ic_conditional ~0
    assert abs(float(_entry(path, vol, 0, 2, 1))) < 1e-12
    assert abs(float(_entry(path, vol, 0, 2, 2)) - 0.36) < 1e-9
    assert float(_entry(path, vol, 0, 2, 7)) < 1e-9
    assert abs(float(_entry(path, vol, 0, 2, 8))) < 1e-9
    assert abs(float(_entry(path, vol, 0, 2, 9)) - 0.36) < 1e-9
    # A,B: marginal 0.6, partial 0.5144957554275265 (they differ!)
    assert abs(float(_entry(path, vol, 0, 1, 9)) - 0.6) < 1e-9
    assert abs(float(_entry(path, vol, 0, 1, 8)) - 0.5144957554275265) < 1e-9
    assert abs(float(_entry(path, vol, 0, 1, 7)) - 0.5144957554275265) < 1e-9
    # Diagonal convention: both couplings 1.0
    for s in (2, 7, 8, 9):
        assert abs(float(_entry(path, vol, 0, 0, s)) - 1.0) < 1e-12
    # Schema stamp present
    doc = px.PhextDoc.load(path)
    assert doc.get_a(vol, px.BOOK_PROVENANCE, 1, 1, 6) == "2"
    assert px.SCHEMA_VERSION == "2"


def test_two_variable_marginal_equals_conditional():
    """In 2D there is nothing to condition on beyond the pair, so
    marginal and conditional coupling coincide: rho = 0.8."""
    rho = 0.8
    corr = np.array([[1.0, rho], [rho, 1.0]])
    prec = np.linalg.inv(corr)
    for kind, M in (("correlation", corr), ("precision", prec)):
        path = _tmp(f"two_var_{kind}.phext")
        vol = px.matrix_to_phext(M, path, kind=kind)
        assert abs(float(_entry(path, vol, 0, 1, 2)) - 0.8) < 1e-12, kind
        assert abs(float(_entry(path, vol, 0, 1, 7)) - 0.8) < 1e-12, kind
        assert abs(float(_entry(path, vol, 0, 1, 8)) - 0.8) < 1e-12, kind
        c = px.coupling_from_phext(path, vol, 0, 1)
        assert abs(c["ic_marginal"] - c["ic_conditional"]) < 1e-12, kind


def test_nonzero_conditional_dependence():
    """A precision matrix with a DIRECT Lambda_AC entry: conditional
    coupling is nonzero and differs from the marginal.
    Lambda = [[2,-.5,.4],[-.5,2,-.5],[.4,-.5,2]] is PD (eigenvalues
    1.465, 1.6, 2.935, checked when this test was written).
    partial(A,C) = -0.4/sqrt(2*2) = -0.2; marginal corr(A,C) of
    inv(Lambda) is -0.146666..., so ic_conditional=0.2 != ic_marginal."""
    M = np.array([[2.0, -0.5, 0.4],
                  [-0.5, 2.0, -0.5],
                  [0.4, -0.5, 2.0]])
    assert np.all(np.linalg.eigvalsh(M) > 0), "test matrix must be PD"
    path = _tmp("direct_ac.phext")
    vol = px.matrix_to_phext(M, path, kind="precision")
    ic_cond = float(_entry(path, vol, 0, 2, 7))
    partial = float(_entry(path, vol, 0, 2, 8))
    ic_marg = float(_entry(path, vol, 0, 2, 2))
    assert abs(ic_cond - 0.2) < 1e-12
    assert abs(partial - (-0.2)) < 1e-12
    assert abs(ic_marg - 0.14666666666666664) < 1e-9
    assert abs(ic_cond - ic_marg) > 0.05


def test_partial_correlations_no_inverse_for_precision():
    """conditional_ic / partial_correlations for kind='precision' must
    not call np.linalg.inv: the input IS the precision matrix."""
    prec = np.linalg.inv(CHAIN_SIGMA)
    orig_inv = np.linalg.inv

    def _boom(*a, **k):
        raise AssertionError("np.linalg.inv called for kind='precision'")

    np.linalg.inv = _boom
    try:
        partial = px.partial_correlations(prec, "precision")
        icc = px.conditional_ic(prec, "precision")
    finally:
        np.linalg.inv = orig_inv
    assert abs(partial[0, 1] - 0.5144957554275265) < 1e-12
    assert abs(partial[0, 2]) < 1e-12
    assert abs(icc[0, 1] - 0.5144957554275265) < 1e-12


def test_coupling_from_phext_schema2():
    prec = np.linalg.inv(CHAIN_SIGMA)
    path = _tmp("chain_api.phext")
    vol = px.matrix_to_phext(prec, path, kind="precision")
    c = px.coupling_from_phext(path, vol, 0, 2)
    assert c["schema_version"] == "2"
    assert abs(c["value"]) < 1e-12
    assert abs(c["ic_marginal"] - 0.36) < 1e-9
    assert c["ic_conditional"] < 1e-9
    assert abs(c["partial_corr"]) < 1e-9
    assert abs(c["marginal_corr"] - 0.36) < 1e-9
    assert c["kind"] == "precision"


def test_schema1_backward_compat():
    """The schema-1 fixture was generated with cf_phext 1.0.0 (fields
    1-6 only, no Book 7 Scroll 6). The schema-2 reader must read it,
    report schema '1', keep field values identical, derive the
    conditional coupling from the stored values, and refuse to invent
    the signed marginal correlation (not stored in schema 1)."""
    fixture = _fixture_path()
    if fixture is None:
        return "SKIP: schema1_chain.phext fixture not found"
    doc = px.PhextDoc.load(fixture)
    assert doc.get_a(1, px.BOOK_PROVENANCE, 1, 1, 6) is None
    assert doc.get_a(1, px.BOOK_R, 1, 3, 7) is None  # no field 7 stored
    # Reconstruction of the stored precision matrix still exact.
    prec = np.linalg.inv(CHAIN_SIGMA)
    assert np.max(np.abs(px.matrix_from_phext(fixture, 1) - prec)) < 1e-12
    c = px.coupling_from_phext(fixture, 1, 0, 2)
    assert c["schema_version"] == "1"
    assert abs(c["value"]) < 1e-12
    assert abs(c["ic_marginal"] - 0.36) < 1e-9
    assert c["ic_conditional"] < 1e-9
    assert abs(c["partial_corr"]) < 1e-9
    assert c["marginal_corr"] is None
    assert c["marginal_corr_signed"] is None
    # A,B through the derived path matches the analytic partial.
    c_ab = px.coupling_from_phext(fixture, 1, 0, 1)
    assert abs(c_ab["ic_conditional"] - 0.5144957554275265) < 1e-9
    assert abs(c_ab["ic_marginal"] - 0.6) < 1e-9


def test_sq_roundtrip():
    sq = os.environ.get("SQ_BIN") or shutil.which("sq") or \
        str(Path.home() / ".cargo" / "bin" / "sq")
    if not sq or not Path(sq).exists():
        return ("SKIP: sq binary not found (checked $SQ_BIN, PATH, "
                "~/.cargo/bin/sq) — SQ interoperability is UNVERIFIED "
                "in this environment")
    src = _tmp("sq_src.phext")
    rng = np.random.default_rng(21)
    A = rng.standard_normal((3, 3))
    M = A @ A.T + 3 * np.eye(3)
    vol = px.matrix_to_phext(M, src, kind="precision")
    # Pick an R-lane coordinate: entry (0,1) value scroll.
    r_coord = px.coord_str(px.addr(vol, px.BOOK_R, 1, 2, 1))
    expected = px.read_scroll(src, r_coord)
    env = dict(os.environ)
    env["PATH"] = str(Path(sq).parent) + os.pathsep + env.get("PATH", "")

    def run(cwd, *args, timeout=15):
        return subprocess.run([sq, *args], cwd=cwd, env=env,
                              capture_output=True, text=True, timeout=timeout)

    # Daemon startup on a shared machine is intermittent (observed:
    # silent no-start with an empty log, then success on a fresh
    # attempt). Try up to 2 fresh work dirs; a SKIP reports BOTH
    # attempts' daemon logs. A started daemon is verified for real.
    logs = []
    for attempt in (1, 2):
        work = TMP / f"sqtest{attempt}"
        shutil.rmtree(work, ignore_errors=True)
        work.mkdir(parents=True)
        phext_file = work / "sq_demo.phext"
        shutil.copyfile(src, phext_file)
        # Daemon output goes to a log FILE, not a PIPE: a daemon that
        # logs more than a pipe buffer would block on write and wedge.
        log_path = work / "sq_daemon.log"
        log_fh = open(log_path, "wb")
        share = subprocess.Popen([sq, "share", phext_file.name], cwd=work,
                                 env=env, stdout=log_fh,
                                 stderr=subprocess.STDOUT)
        try:
            up = False
            for _ in range(40):
                try:
                    r = run(work, "status", timeout=5)
                    if r.returncode == 0 and "Hosting" in r.stdout:
                        up = True
                        break
                except subprocess.TimeoutExpired:
                    pass
                time.sleep(0.5)
            if not up:
                try:
                    share.terminate(); share.wait(timeout=5)
                except Exception:
                    try:
                        share.kill(); share.wait(timeout=5)
                    except Exception:
                        pass
                log_fh.flush()
                logs.append(log_path.read_text(encoding="utf-8",
                                               errors="replace"))
                continue
            toc_out = run(work, "toc").stdout
            assert "1.1.1/1.1.1/1.1.1" in toc_out, \
                f"sq toc missing manifest: {toc_out[:200]}"
            sel = run(work, "select", r_coord).stdout.strip()
            # sq prints "coord: text"
            got = sel.split(": ", 1)[1] if ": " in sel else sel
            assert got == expected, \
                f"sq select {r_coord}: {got!r} != reader {expected!r}"
            return None
        finally:
            try:
                run(work, "shutdown", timeout=10)
            except Exception:
                pass
            try:
                share.wait(timeout=10)
            except Exception:
                share.kill()
            log_fh.close()
    return (f"SKIP: sq present at {sq} but its daemon did not start "
            f"in 2 fresh temp dirs; daemon logs (first 500 chars "
            f"each): {[log[:500] for log in logs]!r}")


ALL_TESTS = [
    test_parser_agreement,
    test_matrix_reconstruction,
    test_diagnose_roundtrip,
    test_windowed_max_addressable,
    test_csv_roundtrip_all,
    test_csv_quoted_field_with_comma,
    test_utf8_whole_file,
    test_chain_marginal_vs_conditional,
    test_two_variable_marginal_equals_conditional,
    test_nonzero_conditional_dependence,
    test_partial_correlations_no_inverse_for_precision,
    test_coupling_from_phext_schema2,
    test_schema1_backward_compat,
    test_sq_roundtrip,
]


def main():
    failures = 0
    skips = 0
    for t in ALL_TESTS:
        try:
            result = t()
            if isinstance(result, str) and result.startswith("SKIP"):
                skips += 1
                print(f"SKIP {t.__name__}: {result[5:]}")
            else:
                print(f"PASS {t.__name__}")
        except Exception as e:  # noqa: BLE001
            failures += 1
            print(f"FAIL {t.__name__}: {type(e).__name__}: {e}")
    passed = len(ALL_TESTS) - failures - skips
    print(f"\n{passed}/{len(ALL_TESTS)} tests passed"
          + (f", {skips} skipped" if skips else ""))
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
