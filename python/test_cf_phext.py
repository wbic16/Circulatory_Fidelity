#!/usr/bin/env python3
"""
Tests for cf_phext. Runnable two ways:

    python3 test_cf_phext.py     (plain runner, prints PASS/FAIL per test)
    pytest test_cf_phext.py      (same functions under pytest)

Covers: parser agreement with the reference phext parser, matrix D+R
reconstruction, diagnose round-trip, CSV round-trip for all 8 upstream
simulation files (field-text exact, incl. quoted fields containing
commas), whole-file UTF-8 validity, schema-2 marginal vs conditional
coupling (chain / 2-variable / direct-dependence cases, no-inverse
conditional path, coupling_from_phext), schema-1 backward
compatibility against a fixture generated by cf_phext 1.0.0, and an
SQ host/select round-trip (SKIP with a printed reason if SQ is absent
or its daemon cannot start; a daemon-start failure includes the
daemon's captured output in the skip reason).
"""

